import { expect, test } from '@playwright/test'

test('evidence desk persists amendments and invalidates reviewed notes after material changes', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'New investigation', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'CASE-1041 evidence desk' })).toBeVisible()
  await page.getByRole('button', { name: 'Prepare investigation', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Refresh demo evidence' })).toBeEnabled({ timeout: 20000 })
  await expect(page.getByText('£45,500', { exact: false }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Inspect SRC-04', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Source SRC-04' })).toContainText('restricted')
  await page.getByRole('button', { name: 'Close source' }).click()
  await page.getByRole('button', { name: '4 Analyze', exact: false }).click()
  await expect(page.getByRole('textbox', { name: 'Stage output', exact: true })).toHaveValue(/94.79%/)
  await page.getByRole('button', { name: 'Draft a challenge' }).click()
  await page.getByRole('button', { name: 'Send message', exact: true }).click()
  await expect(page.getByTestId('latest-assistant-message')).toContainText('Analysis updated', { timeout: 20000 })
  await expect(page.getByRole('textbox', { name: 'Stage output', exact: true })).toHaveValue(/plausible supplier explanation/)
  const amendment = 'Analyst amendment: timing alone does not establish intent. Invoice remains missing [E-01, GAP-01].'
  await page.getByRole('textbox', { name: 'Stage output', exact: true }).fill(amendment)
  await page.getByRole('textbox', { name: 'Reason for stage amendment' }).fill('Preserve the alternative explanation.')
  await page.getByRole('button', { name: '1 Detect', exact: false }).click()
  await page.getByRole('button', { name: '4 Analyze', exact: false }).click()
  await expect(page.getByRole('textbox', { name: 'Stage output', exact: true })).toHaveValue(amendment)
  await expect(page.getByRole('textbox', { name: 'Reason for stage amendment' })).toHaveValue('Preserve the alternative explanation.')
  await page.getByRole('button', { name: 'Apply stage amendment' }).click()
  await expect(page.getByRole('button', { name: 'Apply stage amendment' })).toBeDisabled()
  await page.reload()
  await page.getByRole('button', { name: 'Harbour Components Ltd / CASE-1041', exact: true }).first().click()
  await page.getByRole('button', { name: '4 Analyze', exact: false }).click()
  await expect(page.getByRole('textbox', { name: 'Stage output', exact: true })).toHaveValue(amendment)
  await page.getByRole('button', { name: 'Clarify investigation scope', exact: true }).click()
  await page.getByRole('textbox', { name: 'Investigation scope', exact: true }).fill('Assess permitted supplier evidence, acknowledging the invoice gap.')
  await page.getByRole('button', { name: 'Apply scope and ask agent', exact: true }).click()
  await expect(page.getByText('Scope clarification resolved.', { exact: true })).toBeVisible()
  await expect(page.locator('.task-card')).toHaveCount(3)
  await expect(page.locator('.task-card').last()).toContainText('succeeded', { timeout: 20000 })
  await expect(page.getByRole('button', { name: 'Refresh demo evidence' })).toBeEnabled({ timeout: 20000 })
  await expect(page.getByTestId('latest-assistant-message')).toContainText('Analysis updated', { timeout: 20000 })
  for (const stage of ['1 Detect', '2 Investigate', '3 Gather evidence', '4 Analyze', '5 Human review', '6 Decision']) {
    await page.getByRole('button', { name: stage, exact: false }).click()
    await page.getByRole('button', { name: 'Acknowledge this output' }).click()
    await expect(page.getByRole('button', { name: `${stage} Acknowledged`, exact: true })).toBeVisible()
  }
  await page.getByRole('button', { name: 'Review & record', exact: true }).click()
  await page.getByRole('textbox', { name: 'Analyst rationale' }).fill('All outputs checked; missing invoice and restricted case remain unresolved.')
  await page.getByRole('button', { name: 'Mark note reviewed' }).click()
  await expect(page.getByRole('button', { name: 'Prepare case note' })).toBeEnabled()
  await page.getByRole('button', { name: 'Prepare case note' }).click()
  await expect(page.getByRole('button', { name: 'Copy case note' })).toBeVisible()
  await expect(page.locator('.prepared-note')).toContainText('External saving / approval: unconfirmed')
  await page.getByText('Shared fact across all stages', { exact: true }).click()
  await page.getByRole('textbox', { name: 'Shared beneficiary description' }).fill('Not observed in available history; commercial relationship age unknown.')
  await page.getByRole('textbox', { name: 'Reason for shared fact amendment' }).fill('Avoid equating observation with relationship age.')
  await page.getByRole('button', { name: 'Apply shared fact amendment' }).click()
  await expect(page.getByRole('button', { name: 'Copy case note' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Mark note reviewed' })).toBeDisabled()
  await page.getByText('Revision history', { exact: true }).click()
  const history = page.getByRole('group', { name: 'Investigation revision history' })
  await history.getByRole('button', { name: 'Load older revisions' }).click()
  await expect.poll(() => history.locator('ol > li').count()).toBeGreaterThan(10)
  await page.locator('.investigation-page').evaluate(element => { element.scrollTop = 0 })
  await page.screenshot({ path: 'test-results/investigation-evidence-desk.png', fullPage: true })
  await page.getByRole('button', { name: 'New conversation', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'CASE-1041 evidence desk' })).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toBeEnabled()
  expect(errors).toEqual([])
})

test('the evidence desk remains usable at a narrow viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Toggle history' }).click()
  await page.getByRole('button', { name: 'New investigation', exact: true }).click()
  await page.getByRole('button', { name: 'Prepare investigation', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Refresh demo evidence' })).toBeEnabled({ timeout: 20000 })
  await expect(page.getByRole('navigation', { name: 'Investigation workflow' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
