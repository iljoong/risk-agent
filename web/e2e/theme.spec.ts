import { expect, test } from '@playwright/test'

test('follows the system theme and retains an explicit choice across reloads', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/')
  const toggle = page.getByRole('button', { name: 'Dark mode', exact: true })
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('html')).toHaveCSS('color-scheme', 'dark')
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await page.reload()
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('html')).toHaveCSS('color-scheme', 'light')
  await toggle.focus()
  await page.keyboard.press('Space')
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await page.emulateMedia({ colorScheme: 'light' })
  await page.reload()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
})

test('themes the evidence desk and scope form without losing stage drafts', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto('/')
  await page.getByRole('button', { name: 'New investigation', exact: true }).click()
  await page.getByRole('button', { name: 'Prepare investigation', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Refresh demo evidence' })).toBeEnabled({ timeout: 20000 })
  await page.getByRole('button', { name: '4 Analyze', exact: false }).click()
  const output = page.getByRole('textbox', { name: 'Stage output', exact: true })
  await output.fill('Unsaved analyst draft: retain the missing invoice.')
  await page.getByRole('textbox', { name: 'Reason for stage amendment' }).fill('Preserve uncertainty.')
  await page.getByRole('button', { name: 'Clarify investigation scope', exact: true }).click()
  const scope = page.getByRole('textbox', { name: 'Investigation scope', exact: true })
  await scope.fill('Check the available supplier evidence only.')
  const lightPanel = await page.locator('.investigation-conversation').evaluate(element => getComputedStyle(element).backgroundColor)
  await page.locator('.investigation-page').evaluate(element => { element.scrollTop = 0 })
  await page.screenshot({ path: testInfo.outputPath('evidence-desk-light.png') })
  await page.getByRole('button', { name: 'Dark mode', exact: true }).click()
  await expect(output).toHaveValue('Unsaved analyst draft: retain the missing invoice.')
  await expect(scope).toHaveValue('Check the available supplier evidence only.')
  const darkPanel = await page.locator('.investigation-conversation').evaluate(element => getComputedStyle(element).backgroundColor)
  expect(darkPanel).not.toBe(lightPanel)
  await expect(output).toHaveCSS('color-scheme', 'dark')
  await expect(scope).toHaveCSS('color-scheme', 'dark')
  await page.screenshot({ path: testInfo.outputPath('evidence-desk-dark.png') })
  await scope.scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('scope-and-output-dark.png') })
  await page.getByRole('button', { name: '1 Detect', exact: false }).click()
  await page.getByRole('button', { name: '4 Analyze', exact: false }).click()
  await expect(output).toHaveValue('Unsaved analyst draft: retain the missing invoice.')
})

test('keeps the mobile toggle usable when browser storage is unavailable', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'light' })
  await page.addInitScript(() => {
    Object.defineProperty(window, 'localStorage', {
      get() { throw new DOMException('Storage is blocked', 'SecurityError') },
    })
  })
  await page.goto('/')
  const toggle = page.getByRole('button', { name: 'Dark mode', exact: true })
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Toggle history' }).click()
  await page.getByRole('button', { name: 'New investigation', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'CASE-1041 evidence desk' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Investigation workflow' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('evidence-desk-mobile-dark.png') })
})
