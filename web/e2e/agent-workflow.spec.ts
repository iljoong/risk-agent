import { expect, test } from '@playwright/test'
import path from 'node:path'

test('PDF skill runs independently and saved HTML grounds a follow-up', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('option', { name: 'Proposal OpenAI' }).waitFor({ state: 'attached' })
  await page.getByLabel('Attach PDF', { exact: true }).setInputFiles(path.resolve(import.meta.dirname, '../../.data/e2e/rci-agent/review-notes.pdf'))
  await expect(page.locator('.composer-chips')).toContainText('review-notes.pdf')
  await page.getByRole('button', { name: 'Choose a skill' }).click()
  await page.getByRole('option', { name: /customer-research/ }).click()
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Draft an evidence review report')
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByText('Your task keeps running.', { exact: false })).toBeVisible()
  await expect(page.locator('.task-card .spin')).toBeVisible()
  const title = 'Draft an evidence review report'
  await page.reload()
  await page.getByRole('button', { name: title, exact: true }).first().click()
  const card = page.getByRole('button', { name: /Evidence review draft.*HTML artifact/ })
  await expect(card).toBeVisible({ timeout: 20000 })
  await expect(page.getByRole('button', { name: 'Clear skill', exact: true })).toHaveCount(0)
  await card.click()
  const frame = page.frameLocator('iframe[title="HTML artifact preview"]')
  await expect(frame.getByText('Needs confirmation: source completeness and supporting records.')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: title, exact: true }).first().click()
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Which statements still need evidence?')
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByTestId('latest-assistant-message')).toContainText('Version 1')
  await expect(page.getByTestId('latest-assistant-message')).toContainText('review-notes.pdf, page 1')
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toBeEnabled()
  await card.click()
  await page.screenshot({ path: 'test-results/workspace.png', fullPage: true })
})

test('model choice and clearly disabled future account controls', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('combobox', { name: 'Model', exact: true }).selectOption('claude')
  await expect(page.getByRole('combobox', { name: 'Model', exact: true })).toHaveValue('claude')
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Remember my selected model')
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByTestId('latest-assistant-message')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Remember my selected model', exact: true }).first().click()
  await expect(page.getByRole('combobox', { name: 'Model', exact: true })).toHaveValue('claude')
  await page.getByRole('button', { name: 'Account & access' }).click()
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Manage members' })).toBeDisabled()
})

test('running tasks can be stopped and explicitly retried', async ({ page }) => {
  await page.goto('/')
  const message = page.getByRole('textbox', { name: 'Message', exact: true })
  await expect(message).toBeEnabled()
  await page.getByLabel('Attach PDF', { exact: true }).setInputFiles(path.resolve(import.meta.dirname, '../../.data/e2e/rci-agent/review-notes.pdf'))
  await expect(page.locator('.composer-chips')).toContainText('review-notes.pdf')
  await page.getByRole('button', { name: 'Choose a skill' }).click()
  await page.getByRole('option', { name: /customer-research/ }).click()
  await message.fill('Generate a cancellable draft')
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByText('running', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Stop task', exact: true }).click()
  await expect(page.getByText('cancelled', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Retry task', exact: true }).click()
  await expect(page.getByRole('button', { name: /Evidence review draft.*HTML artifact/ })).toBeVisible({ timeout: 20000 })
  await expect(page.getByText('succeeded', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Clear skill', exact: true })).toHaveCount(0)
  await message.fill('Which statements still need evidence?')
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByTestId('latest-assistant-message')).toContainText('Version 1')
})

test('provider failures stay visible and unsafe Markdown remains inert', async ({ page }) => {
  await page.goto('/')
  const message = page.getByRole('textbox', { name: 'Message', exact: true })
  await expect(message).toBeEnabled()
  await message.fill('Simulate provider failure')
  await page.getByRole('button', { name: 'Send message' }).click()
  await expect(page.getByText('Test provider unavailable. Check model access.', { exact: true })).toBeVisible()
  await expect(message).toBeEnabled()
  await message.fill('Simulate unsafe markdown')
  await page.getByRole('button', { name: 'Send message' }).click()
  const output = page.getByTestId('latest-assistant-message')
  await expect(output).toContainText('Unsafe link')
  await expect(output.locator('img, script, a[href^="javascript:"]')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.dataset.unsafeExecuted)).toBeUndefined()
})
